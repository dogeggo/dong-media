import type { CachePolicy } from './types.ts';

const KiB = 1024;
const MiB = 1024 * KiB;

function policy(
  value: Omit<CachePolicy, 'version' | 'jitterRatio' | 'cacheErrors'> &
    Partial<Pick<CachePolicy, 'version' | 'jitterRatio'>>,
): CachePolicy {
  return {
    version: 1,
    jitterRatio: 0.08,
    cacheErrors: false,
    ...value,
  };
}

