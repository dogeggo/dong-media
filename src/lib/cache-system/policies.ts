export type CachePolicyName = keyof typeof CACHE_POLICIES;

export const ALL_CACHE_POLICIES = Object.freeze(Object.values(CACHE_POLICIES));

const policyByNamespace = new Map(
  ALL_CACHE_POLICIES.map((value) => [value.namespace, value]),
);

export function getCachePolicy(namespace: string): CachePolicy | undefined {
  return policyByNamespace.get(namespace);
}

export function getPoliciesByTag(tag: string): CachePolicy[] {
  return ALL_CACHE_POLICIES.filter((value) => value.tags.includes(tag));
}
